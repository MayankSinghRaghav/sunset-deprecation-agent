# Loading
# ---------------------------------------------------------------------------


def load_fixtures(conn) -> dict:
    """Load all fixtures into an open psycopg connection. Returns row counts."""
    sql_files = sorted(FIX.glob("0*.sql"))
    with conn.cursor() as cur:
        for p in sql_files:
            cur.execute(p.read_text())
        # usage_daily via COPY
        comp = (FIX / "080_usage_daily.csv.zst").read_bytes()
        raw = zstd.ZstdDecompressor().decompress(comp).decode()
        reader = csv.reader(io.StringIO(raw))
        next(reader)  # header
        cur.execute("TRUNCATE usage_daily CASCADE;")
        with cur.copy(
            "COPY usage_daily (feature_id, account_id, day, actor_type, "
            "active_users, events) FROM STDIN"
        ) as cp:
            for row in reader:
                cp.write_row(row)
    conn.commit()

    counts = {}
    with conn.cursor() as cur:
        for t in ["features", "accounts", "feature_dependencies", "contracts",
                  "contract_clauses", "deal_notes", "support_tickets", "usage_daily"]:
            cur.execute(f"SELECT count(*) FROM {t}")
            counts[t] = cur.fetchone()[0]
    return counts
